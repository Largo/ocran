# frozen_string_literal: true
require_relative "build_constants"

module Ocran
  # The RubyGems startup hook that gives a bare interpreter of a packed
  # application the environment of its launch script.
  #
  # The launch script (app.bat / app.sh), the wrapper executable and the
  # self-extracting stub all set the variables Direction#construct exports
  # (GEM_HOME, GEM_PATH, RUBYLIB, SSL_CERT_FILE, ...) before they start
  # bin/ruby. Some hosts can only start the interpreter itself: the Windows
  # service control manager accepts the service dispatcher only from the
  # process it started (error 1063), so a service registered as
  # `bin\ruby.exe src\service.rb` runs without any of them - gems packed
  # outside the Ruby installation are not found, and the CA bundle ocran
  # packed is only used where OpenSSL happens to look on its own.
  #
  # RubyGems requires "rubygems/defaults/operating_system" while it loads,
  # before it computes its paths and before anything of the application
  # runs; distributions use that file to customise RubyGems (RubyInstaller
  # sets up its DLL search paths in it). ocran packs its own file of that
  # name in the packed sitelibdir, which comes first on the default load
  # path. It sets each variable the launch script would set and that is
  # not set yet, resolved against the directory the package is in at run
  # time, and then requires the next operating_system.rb on the load path
  # - the distribution's own - so that keeps working as before.
  #
  # Under the launch script or the stub every variable is already set, so
  # the hook only passes on to the original file there.
  module EnvHook
    include BuildConstants

    # The feature RubyGems requires at startup.
    FEATURE = "rubygems/defaults/operating_system.rb"

    # Builds the hook's source for the variables in +env+ (name => value as
    # exported at build time, with the extraction root placeholder) for a
    # hook packed +depth+ directories below the package root (the depth of
    # the packed sitelibdir plus the two of FEATURE's own directories).
    def self.source(env, depth)
      root_rel = ([".."] * depth).join("/")
      entries = env.map { |name, value|
        "  #{name.to_s.dump} => #{value.to_s.dump},"
      }

      <<~RUBY
        # frozen_string_literal: true
        # Generated by OCRAN. Gives a bare bin/ruby of this package the
        # environment of the launch script: each variable below that is not
        # set yet is set, with "#{EXTRACT_ROOT}/" standing for the package root,
        # and each one the launch script empties is removed, as it does,
        # and then the next #{FEATURE} on the load path (the one the Ruby
        # installation ships, if any) is loaded, as RubyGems would have done.
        # RUBYOPT, LD_LIBRARY_PATH and DYLD_LIBRARY_PATH take effect for child
        # processes only: they are read before this file runs.
        ocran_env = {
        #{entries.join("\n")}
        }
        ocran_root = File.expand_path(#{root_rel.dump}, __dir__)
        ocran_windows = File::ALT_SEPARATOR == "\\\\"
        ocran_same = lambda do |entry, dir|
          entry = File.expand_path(entry)
          ocran_windows ? entry.casecmp?(dir) : entry == dir
        end
        ocran_feature = lambda { |dir| File.join(File.expand_path(dir), #{FEATURE.dump}) }
        ocran_this = lambda { |file| File.file?(file) && File.identical?(file, __FILE__) }
        # RUBYLIB goes where Ruby would have put it: just before the
        # directory this file was found in, the first default entry.
        ocran_index = $LOAD_PATH.index { |dir| ocran_this.call(ocran_feature.call(dir)) } || 0
        ocran_gem_paths = false
        ocran_env.each do |name, value|
          # Removed by the launch script, whatever the parent set: an
          # inherited BUNDLE_GEMFILE must not replace the packaged Gemfile.
          if value.empty?
            ENV.delete(name)
            next
          end
          next if ENV.key?(name)

          value = value.gsub(%r{#{Regexp.escape(EXTRACT_ROOT.to_s)}[/\\\\]}) { "\#{ocran_root}/" }
          value = value.tr("/", "\\\\") if ocran_windows
          ENV[name] = value
          case name
          when "GEM_HOME", "GEM_PATH"
            ocran_gem_paths = true
          when "RUBYLIB"
            dirs = value.split(File::PATH_SEPARATOR).reject(&:empty?).map { |dir| File.expand_path(dir) }
            dirs.reject! { |dir| $LOAD_PATH.any? { |entry| ocran_same.call(entry, dir) } }
            $LOAD_PATH.insert(ocran_index, *dirs.uniq)
          end
        end
        Gem.clear_paths if ocran_gem_paths && defined?(Gem.clear_paths)
        ocran_original = $LOAD_PATH.map(&ocran_feature).find { |file| File.file?(file) && !ocran_this.call(file) }
        require ocran_original if ocran_original
      RUBY
    end
  end
end
