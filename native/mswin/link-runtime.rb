# Links the mswin (MSVC) ocran runtime from the static pieces built by
# build-ruby.cmd: libruby-static, every extension library, the encodings,
# the gem extensions built by build-static-ext.rb, and ocran_main.c.
# Run inside a vcvars64 environment:
#
#   ruby native/mswin/link-runtime.rb BUILD_DIR SRC_DIR OUT.exe [EXT_LINE_FILE...]
require "fileutils"
require "rbconfig"

build, src, out, *ext_files = ARGV.map { |a| a.tr("\\", "/") } # Dir.glob wants /
abort "usage: link-runtime.rb BUILD_DIR SRC_DIR OUT.exe [EXT_LINE_FILE...]" unless out
native = File.expand_path("..", __dir__)
work = File.join(build, "ocran-runtime")
FileUtils.mkdir_p(work)

# Link inputs exactly as Ruby's own makefiles list them (exts.mk).
mk = File.read(File.join(build, "exts.mk")).gsub(/\\\r?\n/, " ")
var = ->(name) { mk[/^#{name} = (.*)$/, 1].to_s.split }
extobjs = var.("EXTOBJS")
extlibs = var.("EXTLIBS")
libpaths = var.("EXTLDFLAGS").grep(/\A-libpath:/)
librubya = Dir[File.join(build, "*-static.lib")].first or abort "no libruby static library in #{build}"
arch_hdr = Dir[File.join(build, ".ext/include/*/ruby/config.h")].first or abort "no config.h"
arch_hdr = File.dirname(File.dirname(arch_hdr))

exts = ext_files.map { |f| File.read(f).split(" ", 4).map(&:strip) }
exts.each do |feature, init, _, _|
  abort "bad extension feature #{feature.inspect}" unless feature.match?(%r{\A[\w/.-]+\z})
  abort "bad init function #{init.inspect}" unless init.match?(/\A\w+\z/)
end

def run(*cmd)
  system(*cmd, exception: true)
end

Dir.chdir(work) do
  run(RbConfig.ruby, File.join(native, "gen-stage0-header.rb"),
      File.join(native, "stage0.rb"), "stage0.h")
  File.write("ocran_exts.c", <<~C)
    /* generated by native/mswin/link-runtime.rb */
    void ruby_init_ext(const char *name, void (*init)(void));
    #{exts.map { |_, init, _, _| "extern void #{init}(void);" }.join("\n")}
    void ocran_init_extra_exts(void)
    {
    #{exts.map { |feature, init, _, _| "    ruby_init_ext(\"#{feature}.so\", #{init});" }.join("\n")}
    }
  C
  # -MT: the static CRT, as everything else was built with.
  cflags = %W[-nologo -MT -O2 -Zi -I. -I#{arch_hdr} -I#{File.join(src, "include")}]
  run("cl", *cflags, "-c", File.join(native, "ocran_main.c"), "-Foocran_main.obj")
  run("cl", *cflags, "-c", "ocran_exts.c", "-Foocran_exts.obj")

  inputs = ["ocran_main.obj", "ocran_exts.obj"]
  inputs += extobjs.map { |o| File.join(build, o) }
  inputs += %w[enc/encinit.obj enc/libenc.lib enc/libtrans.lib].map { |o| File.join(build, o) }
  exts.each { |_, _, lib, _| inputs << lib }
  inputs << librubya
  inputs << File.join(build, "ruby.res")
  libs = extlibs + exts.flat_map { |*, l| l.to_s.split(",") } +
         %w[user32.lib advapi32.lib shell32.lib ws2_32.lib iphlpapi.lib imagehlp.lib shlwapi.lib bcrypt.lib]
  run("cl", "-nologo", "-MT", *inputs, *libs.uniq, "-Fe#{File.expand_path(out)}",
      "-link", "-incremental:no", "-opt:ref", "-opt:icf", "-stack:0x400000",
      "-subsystem:console", *libpaths)
end
puts out
