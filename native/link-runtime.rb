# Links an ocran runtime executable from a kit (see make-kit.rb), adding
# the statically built C extensions of gems:
#
#   ruby native/link-runtime.rb KIT_DIR OUT.exe [EXT_LINE_FILE...]
#
# Each EXT_LINE_FILE holds the line printed by build-static-ext.rb:
#   <feature> <Init function> <archive> <comma-separated libs>
require "fileutils"
require "tmpdir"

kit, out, *ext_files = ARGV
abort "usage: link-runtime.rb KIT_DIR OUT.exe [EXT_LINE_FILE...]" unless out
kit = File.expand_path(kit)

exts = ext_files.map { |f| File.read(f).split(" ", 4).map(&:strip) }
exts.each do |feature, init, _, _|
  abort "bad extension feature #{feature.inspect}" unless feature.match?(%r{\A[\w/.-]+\z})
  abort "bad init function #{init.inspect}" unless init.match?(/\A\w+\z/)
end

args = File.read(File.join(kit, "link.args")).lines(chomp: true)
cc = args.first

Dir.mktmpdir do |tmp|
  src = File.join(tmp, "ocran_exts.c")
  File.write(src, <<~C)
    /* generated by native/link-runtime.rb */
    void ruby_init_ext(const char *name, void (*init)(void));
    #{exts.map { |_, init, _, _| "extern void #{init}(void);" }.join("\n")}
    void ocran_init_extra_exts(void)
    {
    #{exts.map { |feature, init, _, _| "    ruby_init_ext(\"#{feature}.so\", #{init});" }.join("\n")}
    }
  C
  obj = File.join(tmp, "ocran_exts.o")
  system(cc, "-O2", "-c", src, "-o", obj, exception: true)

  extra = [obj]
  exts.each do |_, _, archive, libs|
    extra << archive
    extra.concat(libs.to_s.split(",")) # -lffi etc.: found in @KIT@/deps
  end
  cmd = args.flat_map { |a| a == "@EXTRA@" ? extra : [a] }.map { |a| a.gsub("@KIT@", kit) }
  system(*cmd, "-o", out, exception: true)
end
strip = args.first.sub(/gcc\z/, "strip")
system(strip, out, exception: true)
puts out
